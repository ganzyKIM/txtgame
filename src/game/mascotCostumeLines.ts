export function costumeTouchLine(costume: Costume, form: Form, rand: () => number = Math.random): string {
  const arr = COSTUME_LINES[costume][form].touch;
  return arr[Math.floor(rand() * arr.length) % arr.length];
}

export function costumeUnlockLine(costume: Costume, form: Form, rand: () => number = Math.random): string {
  const arr = COSTUME_LINES[costume][form].unlock;
  return arr[Math.floor(rand() * arr.length) % arr.length];
}
