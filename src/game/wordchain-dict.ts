/** 단어 배열로부터 Dict(검증 + 시작글자 인덱스)를 만든다 */
export function buildDict(words: string[]): Dict {
  const set = new Set(words);
  const index = new Map<string, string[]>();
  for (const w of set) {
    const f = firstChar(w);
    const arr = index.get(f);
    if (arr) arr.push(w);
    else index.set(f, [w]);
  }
  return {
    has: (word) => set.has(word),
    byFirst: (ch) => index.get(ch) ?? [],
  };
}

